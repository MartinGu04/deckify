/**
 * Generates docs/media/deck-layout-overview.svg: an illustration of a Deckify layout on a 5×3 Stream Deck, assembled from Deckify's own key
 * images exactly as the plugin ships them (no Spotify artwork, no album art, no track data, no Elgato hardware render). Run with
 * `npm run assets`; `test/docs.test.ts` fails when the committed file differs from this output.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const IMAGES = path.join(ROOT, "com.marting.deckify.sdPlugin", "imgs", "actions");
export const OVERVIEW_FILE = path.join(ROOT, "docs", "media", "deck-layout-overview.svg");

/** The layout, row by row: [key image (relative to imgs/actions), caption]; `null` is a free key. */
export const OVERVIEW_LAYOUT = [
	[
		["playback/previous.svg", "Previous"],
		["playback/pause.svg", "Play / Pause"],
		["playback/next.svg", "Next"],
		["playback/now-playing.svg", "Now Playing"],
		["library/like-unavailable.svg", "Like / Unlike"],
	],
	[
		["volume/volume-down.svg", "Volume Down"],
		["volume/speaker.svg", "Mute / Unmute"],
		["volume/volume-up.svg", "Volume Up"],
		["playlist/add.svg", "Add to Playlist"],
		["playlist/play.svg", "Play Playlist"],
	],
	[["spotify-account/connected.svg", "Spotify Account"], null, null, null, null],
];

const KEY = 112;
const GAP_X = 36;
const GAP_Y = 52;
const PAD = 40;
const TOP = 64;
const FONT = "'Segoe UI', Inter, 'Helvetica Neue', Arial, sans-serif";

/**
 * Builds the illustration.
 * @param {(file: string) => string} read Reads a key image (path relative to imgs/actions).
 * @returns {string} The SVG document.
 */
export function deckOverviewSvg(read = (file) => fs.readFileSync(path.join(IMAGES, file), "utf8")) {
	const columns = OVERVIEW_LAYOUT[0].length;
	const width = PAD * 2 + columns * KEY + (columns - 1) * GAP_X;
	const height = TOP + OVERVIEW_LAYOUT.length * (KEY + GAP_Y) + 4;
	const keys = [];
	OVERVIEW_LAYOUT.forEach((row, r) => {
		row.forEach((cell, c) => {
			const x = PAD + c * (KEY + GAP_X);
			const y = TOP + r * (KEY + GAP_Y);
			if (cell === null) {
				keys.push(`\t<rect x="${x}" y="${y}" width="${KEY}" height="${KEY}" rx="16" fill="#1B1D22" stroke="#2A2D34" stroke-width="2"/>`);
				return;
			}
			const [file, caption] = cell;
			// Each key image is embedded unchanged; only its root element gets a position and size.
			const image = read(file)
				.replaceAll("\r\n", "\n")
				.trim()
				.replace(/^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="72" height="72" viewBox="0 0 144 144">/, `<svg x="${x}" y="${y}" width="${KEY}" height="${KEY}" viewBox="0 0 144 144">`)
				.split("\n")
				.map((line) => `\t\t${line}`)
				.join("\n");
			if (!image.includes(`<svg x="${x}"`)) {
				throw new Error(`Unexpected key image format: ${file}`);
			}
			keys.push(`\t<g clip-path="url(#key)">\n${image}\n\t</g>`);
			keys.push(
				`\t<text x="${x + KEY / 2}" y="${y + KEY + 26}" font-family="${FONT}" font-size="15" font-weight="600" fill="#8B949E" text-anchor="middle">${caption}</text>`,
			);
		});
	});
	return [
		`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
		`\t<title>Illustration of a Deckify layout on a 5×3 Stream Deck, built from Deckify's own key images</title>`,
		`\t<!-- Generated by scripts/export-deck-overview.mjs from com.marting.deckify.sdPlugin/imgs/actions. Not a photo; no Spotify artwork or track data. -->`,
		`\t<defs><clipPath id="key" clipPathUnits="objectBoundingBox"><rect width="1" height="1" rx="0.14"/></clipPath></defs>`,
		`\t<text x="${PAD}" y="36" font-family="${FONT}" font-size="15" font-weight="700" letter-spacing="1" fill="#8B949E">ILLUSTRATION · EXAMPLE 5×3 LAYOUT · FREE KEYS FOR MORE PLAYLISTS</text>`,
		...keys,
		`</svg>`,
		``,
	].join("\n");
}

if (import.meta.main) {
	fs.mkdirSync(path.dirname(OVERVIEW_FILE), { recursive: true });
	fs.writeFileSync(OVERVIEW_FILE, deckOverviewSvg());
	console.log(`  wrote ${path.relative(process.cwd(), OVERVIEW_FILE)}`);
}
